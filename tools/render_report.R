args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 1L) stop("Usage: Rscript tools/render_report.R path/to/report.Rmd")
project <- normalizePath(Sys.getenv("LEC_PROJECT_ROOT", unset = getwd()), winslash = "/", mustWork = TRUE)
if (!file.exists(file.path(project, "config", "workflow.json"))) stop("Run from the repository root or set LEC_PROJECT_ROOT.")
report <- normalizePath(args[[1]], winslash = "/", mustWork = TRUE)
if (!startsWith(report, paste0(project, "/"))) stop("Report must be inside this repository.")
if (!requireNamespace("rmarkdown", quietly = TRUE)) stop("Install the documented R environment first.")
setwd(project)
rmarkdown::render(report, knit_root_dir = project, params = list(project_root = project))
